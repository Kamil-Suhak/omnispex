#[allow(clippy::too_many_arguments)]
fn op(
    id: &str,
    name: &str,
    faction_id: &str,
    faction_name: &str,
    role: &str,
    apl: u32,
    movement: u32,
    save: u32,
    wounds: u32,
    max_per_kill_team: u32,
    weapons: Vec<KtWeaponProfile>,
    abilities: Vec<(&str, &str)>,
    keywords: Vec<&str>,
) -> OperativeDatacard {
    OperativeDatacard {
        id: id.to_string(),
        name: name.to_string(),
        faction_id: faction_id.to_string(),
        faction_name: faction_name.to_string(),
        role: role.to_string(),
        apl,
        movement,
        save,
        wounds,
        weapons,
        abilities: abilities
            .into_iter()
            .map(|(n, d)| KtAbilityData {
                name: n.to_string(),
                description: d.to_string(),
            })
            .collect(),
        keywords: keywords.into_iter().map(|k| k.to_string()).collect(),
        max_per_kill_team,
    }
}

